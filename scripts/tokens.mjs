// Generates src/tokens.css from tokens/tokens.json (the single source of truth).
// Names follow Tailwind v4 (--color-neutral-800, --text-sm, --radius-3xl…) for primitives
// and shadcn (--background, --primary-foreground…) for semantic tokens, same as in Figma.
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'));
const p = t.primitives;
const s = t.semantic;

// "neutral.800" → var(--color-neutral-800); "white/10" → white at 10% opacity
const ref = (v) => {
  const [name, alpha] = v.split('/');
  const css = `var(--color-${name.replace('.', '-')})`;
  return alpha ? `color-mix(in srgb, ${css} ${alpha}%, transparent)` : css;
};
const block = (sel, lines) => `${sel} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;

const prim = [];
for (const [fam, val] of Object.entries(p.color)) {
  if (typeof val === 'string') prim.push(`--color-${fam}: ${val};`);
  else for (const [step, hex] of Object.entries(val)) prim.push(`--color-${fam}-${step}: ${hex};`);
}
prim.push(`--font-sans: ${p.font.sans};`, `--font-mono: ${p.font.mono};`);
for (const [k, [size, lh]] of Object.entries(p.text)) prim.push(`--text-${k}: ${size}px;`, `--text-${k}--line-height: ${lh}px;`);
for (const [k, w] of Object.entries(p['font-weight'])) prim.push(`--font-weight-${k}: ${w};`);
for (const [k, v] of Object.entries(p.tracking)) prim.push(`--tracking-${k}: ${v};`);
for (const [k, r] of Object.entries(p.radius)) prim.push(`--radius-${k}: ${r}px;`);
prim.push('--spacing: 4px;');

const sem = (obj) => Object.entries(obj).map(([k, v]) => `--${k}: ${ref(v)};`);

const out =
  '/* Generated by scripts/tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n\n' +
  block(':root', prim) + '\n' +
  '/* semantic: dark is the default theme */\n' +
  block(s.scopes.dark, [...sem(s.dark), ...sem(s.static)]) + '\n' +
  '/* semantic: light surfaces (sheets, drawers, the movement form) */\n' +
  block(s.scopes.light, sem(s.light)) + '\n' +
  '/* controls sitting on a card step up one level so they never blend into it */\n' +
  block(s.elevate, ['--secondary: var(--secondary-on-card);']) + '\n' +
  '/* type roles: same names as the Figma text styles (Heading/H1 → .type-heading-h1) */\n' +
  Object.entries(t.typography).map(([role, [size, weight, track]]) =>
    `.type-${role} { font-size: var(--text-${size}); line-height: var(--text-${size}--line-height); font-weight: var(--font-weight-${weight}); letter-spacing: var(--tracking-${track}); }`).join('\n') + '\n';

writeFileSync(new URL('../src/tokens.css', import.meta.url), out);
console.log('tokens.css written');
